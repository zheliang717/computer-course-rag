import { expect, test } from '@playwright/test'
import { randomUUID } from 'node:crypto'

test('教师可在新版题库和课程公告中查询翻页并维护记录', async ({ page }) => {
  test.setTimeout(90_000)
  const marker=randomUUID().slice(0,8), title='页面管理演示题-'+marker, notice='页面管理演示公告-'+marker
  page.on('dialog', dialog => dialog.accept())
  await page.route('**/api/v1/auth/login',async route=>{
    const response=await route.fetch()
    if(response.status()===200){
      const token=(await response.json()).access_token
      const owner=JSON.parse(Buffer.from(token.split('.')[0],'base64url').toString()).sub
      await page.evaluate(owner=>localStorage.setItem('rag_update_notice:'+owner,'2026-10-29-zhixue-assistant'),owner)
    }
    await route.fulfill({response})
  })
  await page.goto('/')
  await page.getByLabel('登录账号',{exact:true}).fill('teacher')
  await page.getByPlaceholder('输入登录密码',{exact:true}).fill('teacher123')
  await page.getByRole('button',{name:'登录课程空间',exact:true}).click()
  const nav=page.getByRole('navigation',{name:'平台导航'})
  await nav.getByRole('button',{name:'题库管理'}).click()
  const bank=page.getByRole('region',{name:'题库查询'})
  await expect(bank.locator('.qd-row')).toHaveCount(10)
  await bank.getByRole('button',{name:'下一页'}).click()
  await expect(bank.locator('.list-pager')).toContainText('第 2 /')
  await bank.getByRole('button',{name:'新建题目'}).click()
  let editor=page.getByRole('dialog',{name:'新建题目',exact:true})
  await editor.getByRole('combobox',{name:'所属课程',exact:true}).selectOption({label:'数据结构与算法'})
  await editor.getByLabel('题目类型').selectOption('true_false')
  await editor.getByLabel('题干',{exact:true}).fill(title)
  await editor.getByLabel('选项',{exact:true}).fill('正确，错误')
  await editor.getByLabel('正确答案',{exact:true}).fill('正确')
  await editor.getByRole('button',{name:'加入题库',exact:true}).click()
  await expect(editor).not.toBeVisible()
  await bank.getByLabel('题干或知识点').fill(title)
  await bank.getByRole('button',{name:'查询',exact:true}).click()
  await expect(bank.locator('.qd-row')).toHaveCount(1)
  await bank.locator('.qd-row').click()
  await page.getByRole('dialog').getByRole('button',{name:'编辑题目',exact:true}).click()
  editor=page.getByRole('dialog',{name:'编辑题目',exact:true})
  await editor.getByLabel('题干',{exact:true}).fill(title+'-已编辑')
  await editor.getByRole('button',{name:'保存题目',exact:true}).click()
  await expect(bank.locator('.qd-row')).toContainText(title+'-已编辑')
  await bank.locator('.qd-row').click()
  await page.getByRole('dialog').getByRole('button',{name:'删除题目',exact:true}).click()
  await page.getByRole('dialog',{name:'确认删除题目？',exact:true}).getByRole('button',{name:'确认删除',exact:true}).click()
  await expect(bank.locator('.qd-row')).toHaveCount(0)
  await nav.getByRole('button',{name:'教学课程'}).click()
  await page.getByLabel('搜索课程').fill('DSA-2026')
  await page.locator('.course-directory').getByRole('button',{name:'搜索',exact:true}).click()
  await page.locator('.course-card').filter({hasText:'数据结构与算法'}).first().click()
  const notices=page.locator('.course-announcement-panel')
  await expect(notices.locator('.course-announcement-list article')).toHaveCount(5)
  await notices.getByRole('button',{name:'下一页'}).click()
  await expect(notices.locator('.list-pager')).toContainText('第 2 /')
  await notices.getByText('发布课程公告',{exact:true}).click()
  await notices.getByPlaceholder('公告标题').fill(notice)
  await notices.locator('textarea').fill('仅独立测试副本中的页面验收公告。')
  await notices.getByRole('button',{name:'发布到本课程',exact:true}).click()
  const row=notices.locator('.course-announcement-list article').filter({hasText:notice})
  await expect(row).toBeVisible()
  await row.getByRole('button',{name:'编辑',exact:true}).click()
  await notices.getByPlaceholder('公告标题').fill(notice+'-已编辑')
  await notices.getByRole('button',{name:'保存公告',exact:true}).click()
  await expect(row).toContainText(notice+'-已编辑')
  await row.getByRole('button',{name:'删除',exact:true}).click()
  await expect(row).toHaveCount(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(2)
})
