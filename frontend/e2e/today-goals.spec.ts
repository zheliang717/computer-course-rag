const tokens=new Map<string,string>()
async function login(page:Page,role:'teacher'|'admin') {
  let token=tokens.get(role)
  if(!token) {
    const response=await page.request.post('/api/v1/auth/login',{data:{username:role,password:role+'123'}})
    expect(response.status()).toBe(200);token=(await response.json()).access_token as string;tokens.set(role,token)
  }
  const owner=JSON.parse(Buffer.from(token!.split('.')[0],'base64url').toString()).sub
  const budget=await page.request.get('/api/v1/auth/me',{headers:{Authorization:'Bearer '+token}})
  if(budget.status()===429 || Number(budget.headers()['x-ratelimit-remaining']||300)<160) {
    test.setTimeout(test.info().timeout+65_000)
    await page.waitForTimeout(30_000);await page.waitForTimeout(30_000);await page.waitForTimeout(1_000)
  }
  await page.addInitScript(({token,owner})=>{
    localStorage.setItem('rag_token',token)
    localStorage.setItem('rag_update_notice:'+owner,'2026-10-29-zhixue-assistant')
  },{token:token!,owner})
  await page.goto('/')
  await expect(page.getByRole('navigation',{name:'平台导航'})).toBeVisible()
  return {Authorization:'Bearer '+token}
}
async function course(page:Page,headers:Record<string,string>) {
  const response=await page.request.get('/api/v1/courses',{headers})
  expect(response.ok()).toBeTruthy()
  return (await response.json()).find((row:any)=>row.code==='DSA-2026')
}
async function fit(page:Page) {
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(2)
  for(const dialog of await page.locator('dialog[open]').all()) {
    expect(await dialog.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(2)
  }
}
