test('今日目标：定位反馈进入教师审核并向学生回传意见',async({page},info)=>{
  test.setTimeout(90_000)
  const headers=await login(page,'teacher'),c=await course(page,headers), marker=randomUUID().slice(0,8)
  const auth=await page.request.post('/api/v1/auth/login',{data:{username:'student',password:'student123'}})
  expect(auth.status()).toBe(200)
  const student={Authorization:'Bearer '+(await auth.json()).access_token}
  const bases=await(await page.request.get('/api/v1/courses/'+c.id+'/knowledge-bases',{headers})).json()
  const response=await page.request.post('/api/v1/questions/ask',{headers:student,timeout:60_000,data:{request_id:randomUUID(),question:'二分查找为什么每轮排除中点？ '+marker,answer_mode:'rag',knowledge_base_id:bases[0].id,assistant_scope:'course_qa',assistant_course_id:c.id}})
  expect(response.status()).toBe(200)
  const answer=await response.json(),quote=Array.from(answer.answer as string).slice(0,25).join('')
  const path='/api/v1/history/'+answer.history_id+'/annotations'
  const created=await page.request.post(path,{headers:student,data:{answer_quote:quote,start_offset:0,end_offset:Array.from(quote).length,category:'unclear',comment:'请补充边界示例 '+marker}})
  expect(created.status()).toBe(201)
  await page.getByRole('navigation',{name:'平台导航'}).getByRole('button',{name:'题库管理'}).click()
  await page.getByRole('group',{name:'题库管理分类'}).getByRole('button',{name:/问答审核/}).click()
  await page.getByRole('checkbox',{name:'只看有定位反馈的问答'}).check()
  const row=page.locator('.review-card').filter({hasText:marker})
  await row.getByRole('button',{name:/查看定位反馈/}).click()
  await expect(row.locator('.feedback-review blockquote')).toHaveText(quote)
  await row.getByLabel('审核意见',{exact:true}).fill('已核对，请补充边界收缩的例子。')
  await row.getByRole('button',{name:'驳回并记录',exact:true}).click()
  await expect(row.locator('.review-status')).toHaveText('已驳回')
  const result=await(await page.request.get(path,{headers:student})).json()
  expect(result.items[0].review_note).toBe('已核对，请补充边界收缩的例子。')
  expect(result.items[0].answer_quote).toBe(quote)
  await fit(page)
  await page.screenshot({path:info.outputPath('answer-feedback-loop.png'),fullPage:true})
})
